/** OpenCode's heading over an instruction file it sends, and its notices that one changed or went. */
const INSTRUCTION_PATHS = /^(?:Instructions from: (?<file>.+)|The instructions from (?<notice>.+?) (?:no longer apply\.|changed\. Here's the diff:))$/gm;
/** Where the next thing OpenCode sends starts, after an instruction file (it joins them with a line break). */
const AFTER_INSTRUCTIONS = /\n+(?=Instructions from: |New instructions apply from:\n|The instructions from |The instructions changed:\n|Skills provide specialized instructions|The available skills have changed|New skills are available)/g;
/** The headings OpenCode puts over an instruction file that is new or changed. */
const INSTRUCTION_NOTICES = ['New instructions apply from:\n', 'The instructions changed:\n'];
/** OpenCode's notice that skills went, and the ids it lists. */
const GONE_SKILLS_LEAD = 'The following skill IDs are no longer available and must not be used: ';
const GONE_SKILLS = new RegExp(`^${GONE_SKILLS_LEAD}(?<ids>.+)\\.$`, 'gm');
/** What is left of a text that held only instructions or skills from outside the folders. Some providers refuse an empty text. */
export const LEFT_OUT = 'Instructions and skills from outside the folders open in the window were left out.';

/** `value` matched as it is in a regular expression. */
function escapeRegExp(value: string): string {
	return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/** `text` without `start`..`end`, the line breaks around it as wide as the wider of the two, and none at either end. */
function cut(text: string, start: number, end: number): string {
	const before = text.slice(0, start).replace(/\n+$/, '');
	const after = text.slice(end).replace(/^\n+/, '');
	if (!before || !after) {
		return before + after;
	}
	return before + '\n'.repeat(Math.max(start - before.length, text.length - end - after.length)) + after;
}

/** `text` without what `pattern` (global) matches. */
function cutAll(text: string, pattern: RegExp): string {
	let result = text;
	pattern.lastIndex = 0;
	for (let match = pattern.exec(result); match; pattern.lastIndex = 0, match = pattern.exec(result)) {
		result = cut(result, match.index, match.index + match[0].length);
	}
	return result;
}

/**
 * Takes out of a text OpenCode sends the model the instruction files and skills it found outside the
 * folders open in the window. OpenCode reads its global AGENTS.md and the AGENTS.md in every folder
 * from the open one up to the home folder itself, with no setting to stop it, and lists the user's own
 * skills (`~/.claude/skills`, `~/.agents/skills`, its config folder's).
 *
 * @param instructions Each instruction file outside the folders, and what it holds now: the exact text
 * comes out; one changed since OpenCode read it comes out up to what OpenCode sends after it.
 * @param skills The ids of the skills outside the folders.
 */
export function withoutOutside(text: string, instructions: ReadonlyMap<string, string | undefined>, skills: readonly string[]): string {
	let result = text;
	for (const [file, content] of instructions) {
		const escaped = escapeRegExp(file);
		result = cutAll(result, new RegExp(`^The instructions from ${escaped} changed\\. Here's the diff:\\n\`\`\`diff\\n[\\s\\S]*?\\n\`\`\`$`, 'gm'));
		result = cutAll(result, new RegExp(`^The instructions from ${escaped} no longer apply\\.$`, 'gm'));
		const heading = `Instructions from: ${file}\n`;
		for (let start = result.indexOf(heading); start >= 0; start = result.indexOf(heading)) {
			let end: number;
			if (content !== undefined && result.startsWith(heading + content, start)) {
				end = start + heading.length + content.length;
			} else {
				AFTER_INSTRUCTIONS.lastIndex = start + heading.length;
				end = AFTER_INSTRUCTIONS.exec(result)?.index ?? result.length;
			}
			const notice = INSTRUCTION_NOTICES.find(notice => start >= notice.length && result.startsWith(notice, start - notice.length));
			result = cut(result, start - (notice?.length ?? 0), end);
		}
	}
	if (skills.length) {
		for (const id of skills) {
			result = cutAll(result, new RegExp(`^[ \\t]*<skill>\\n[ \\t]*<id>${escapeRegExp(id)}</id>\\n[\\s\\S]*?</skill>$`, 'gm'));
		}
		result = cutAll(result, /^New skills are available in addition to those previously listed:$(?!\n[ \t]*<skill>)/gm);
		for (const match of [...result.matchAll(GONE_SKILLS)].reverse()) {
			const left = match.groups!.ids.split(', ').filter(id => !skills.includes(id));
			const end = match.index + match[0].length;
			result = left.length ? `${result.slice(0, match.index)}${GONE_SKILLS_LEAD}${left.join(', ')}.${result.slice(end)}` : cut(result, match.index, end);
		}
	}
	return result || !text ? result : LEFT_OUT;
}

/**
 * Rewrites a model request, as OpenCode's `session` → `context` hook allows, without the instruction
 * files and skills outside the folders open in the window (`withoutOutside`): its system prompt, and
 * the text OpenCode adds to the conversation when instructions or skills change.
 */
export function confineRequest(request: ModelRequest, folders: readonly string[], skills: readonly string[]): void {
	const parts = [...request.system, ...request.messages.flatMap(message => Array.isArray(message.content) ? message.content as RequestPart[] : [])]
		.filter(part => part?.type === 'text' && typeof part.text === 'string');
	const files = [...new Set(parts.flatMap(part => [...part.text!.matchAll(INSTRUCTION_PATHS)].map(match => match.groups!.file ?? match.groups!.notice)))]
		.filter(file => path.isAbsolute(file) && outsideFolders(file, folders));
	if (!files.length && !skills.length) {
		return;
	}
	const instructions = new Map(files.map(file => {
		try {
			return [file, readFileSync(file, 'utf8')] as const;
		} catch {
			return [file, undefined] as const;
		}
	}));
	for (const part of parts) {
		part.text = withoutOutside(part.text!, instructions, skills);
	}
}

