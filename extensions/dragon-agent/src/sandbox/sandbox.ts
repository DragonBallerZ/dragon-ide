/*
 * The macOS sandbox agents' shell commands run in. OpenCode's file tools are kept to the folders
 * open in the window by permission rules (`confinementConfig`); a shell command reaches whatever
 * its process can, so on macOS each one runs under `sandbox-exec` with a profile that closes the
 * home folders and other disks except for the open folders. The sandbox plugin
 * (`opencodePlugin.ts`) swaps the command's shell for a wrapper that does this.
 *
 * This module does not import `vscode`: the plugin and the tests use it too.
 */

import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, readlinkSync, realpathSync, renameSync, statSync, writeFileSync } from 'node:fs';
import { chmod, mkdir, readdir, readFile, readlink, realpath, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import * as path from 'node:path';

const SANDBOX_EXEC = '/usr/bin/sandbox-exec';

export interface SandboxProfileInput {
	/** The folders commands may read and write: those open in the window, their worktrees and Git folders. Real paths. */
	readonly folders: readonly string[];
	/** The home folder commands are given in place of the real one. A real path. */
	readonly home: string;
	/** Folders commands may read but not change: the toolchains in the home folder that are on `PATH`. Real paths. */
	readonly readOnly: readonly string[];
	/** Folders closed to commands except for the ones above: the home folders and other disks. Real paths. */
	readonly closed: readonly string[];
	/** Folders no command may change, even inside an open folder: the sandbox's own profile. Real paths. */
	readonly sealed?: readonly string[];
}

/** A path as a sandbox profile string. */
function quote(value: string): string {
	return `"${value.replace(/[\\"]/g, c => `\\${c}`)}"`;
}

function inside(parent: string, child: string): boolean {
	const rel = path.relative(parent, child);
	return rel === '' || (!rel.startsWith('..') && !path.isAbsolute(rel));
}

/**
 * The sandbox profile for agents' shell commands. Everything else a process may do stays allowed,
 * so compilers, package managers and dev servers work as usual, but:
 * - nothing under a closed folder is read or written, except the open folders, the command's own
 *   home folder and the toolchains on `PATH`; the folders above them can be listed, which Git and
 *   Node need;
 * - nothing is written outside those folders and the temp folders;
 * - no Unix socket is connected to, which keeps commands from Docker, ssh-agent and the editor,
 *   except the one name lookups go through;
 * - no app is opened and no Apple event sent, which would run code outside the sandbox;
 * - the clipboard and apps' preferences (`defaults`), which macOS serves from outside the
 *   process, are not read.
 */
export function sandboxProfile(input: SandboxProfileInput): string {
	const writable = [...input.folders, input.home];
	const ancestors = new Set<string>();
	for (const folder of [...writable, ...input.readOnly]) {
		for (const root of input.closed.filter(root => inside(root, folder))) {
			for (let dir = path.dirname(folder); inside(root, dir); dir = path.dirname(dir)) {
				ancestors.add(dir);
				if (dir === root) {
					break;
				}
			}
		}
	}
	const subpaths = (folders: Iterable<string>) => [...folders].map(folder => `(subpath ${quote(folder)})`).join(' ');
	const literals = (folders: Iterable<string>) => [...folders].map(folder => `(literal ${quote(folder)})`).join(' ');
	return [
		'(version 1)',
		'; Generated by Dragon IDE for agents\' shell commands.',
		'(allow default)',
		// A later rule wins over an earlier one.
		'(deny file-write*)',
		'(allow file-write* (subpath "/private/tmp") (subpath "/private/var/folders") (subpath "/dev"))',
		...(input.closed.length ? [`(deny file-read* file-write* ${subpaths(input.closed)})`] : []),
		...(ancestors.size ? [`(allow file-read* ${literals([...ancestors].sort())})`] : []),
		...(input.readOnly.length ? [`(allow file-read* ${subpaths(input.readOnly)})`] : []),
		`(allow file-read* file-write* ${subpaths(writable)})`,
		...(input.sealed?.length ? [`(deny file-write* ${subpaths(input.sealed)})`] : []),
		'(deny network-outbound (remote unix-socket))',
		'(allow network-outbound (remote unix-socket (path-literal "/private/var/run/mDNSResponder")))',
		'(deny lsopen)',
		'(deny appleevent-send)',
		'(deny mach-lookup (global-name "com.apple.pasteboard.1"))',
		'(deny user-preference-read user-preference-write)',
		'',
	].join('\n');
}

/** The symbolic links met on the way to the file a path names: following them means reading them. */
async function linksOnTheWay(file: string): Promise<string[]> {
	const links: string[] = [];
	let pending = file.split(path.sep).filter(part => part);
	let current: string = path.sep;
	for (let hops = 0; pending.length && hops < 40;) {
		const next = path.join(current, pending.shift()!);
		const target = await readlink(next).catch(() => undefined);
		if (target === undefined) {
			current = next;
			continue;
		}
		hops++;
		links.push(next);
		pending = [...path.resolve(current, target).split(path.sep).filter(part => part), ...pending];
		current = path.sep;
	}
	return links;
}

/**
 * Where version managers keep the interpreters in the home folder. A project's virtual environment
 * or `.nvmrc` runs one that is not on `PATH`. They hold programs, not the user's files.
 */
const INTERPRETERS = ['.local/share/uv/python', '.pyenv', '.nvm', '.volta', '.rustup', '.asdf/installs', '.local/share/mise/installs', '.sdkman/candidates'];

/**
 * The folders in the home folder that commands need to read to run the tools there: each folder on
 * `PATH` in the home folder, the folders its links point into (`~/.local/bin/python3.13` links to
 * `…/cpython-3.13/bin/python3.13`, a link to `…/cpython-3.13.14/bin/python3.13`, whose library is
 * in `…/cpython-3.13.14/lib`), and the version managers' interpreters. Not the folders around them:
 * `~/.cargo` also holds the crates.io token. Real paths.
 */
export async function toolchainFolders(pathEnv: string, home: string): Promise<string[]> {
	const realHome = await realpath(home).catch(() => home);
	const folders = new Set<string>();
	for (const entry of pathEnv.split(path.delimiter).filter(entry => path.isAbsolute(entry))) {
		const real = await realpath(entry).catch(() => undefined);
		if (!real || real === realHome || !inside(realHome, real)) {
			continue;
		}
		folders.add(real);
		for (const name of await readdir(real).catch(() => [])) {
			const target = await realpath(path.join(real, name)).catch(() => undefined);
			if (target && !inside(real, target)) {
				const dir = path.dirname(target);
				folders.add(path.basename(dir) === 'bin' ? path.dirname(dir) : dir);
				for (const link of await linksOnTheWay(path.join(real, name))) {
					if (!inside(real, link)) {
						folders.add(link);
					}
				}
			}
		}
	}
	for (const store of INTERPRETERS) {
		const real = await realpath(path.join(realHome, store)).catch(() => undefined);
		if (real) {
			folders.add(real);
		}
	}
	return [...folders].sort();
}

/** Server variables a command must not see: the server's password, Dragon's and the editor's handles. */
const PRIVATE_PREFIXES = /^(OPENCODE_|DRAGON_|VSCODE_|ELECTRON_)/;
/** Variables that look like credentials, which a project's commands get from the project instead. */
const CREDENTIAL = /(^|_)(TOKEN|SECRET|PASSWORD|PASSWD|PASSPHRASE|CREDENTIALS?|API_?KEY|ACCESS_KEY|PRIVATE_KEY|AUTH)(_|$)/i;
const AGENT_SOCKETS = new Set(['SSH_AUTH_SOCK', 'GPG_AGENT_INFO']);

/**
 * The environment for an agent's shell command, from the server's: without the server's password
 * (which would open OpenCode's API, and every file through it), Dragon's and the editor's handles,
 * agent sockets and variables that look like credentials. `OPENCODE_TERMINAL`, which OpenCode sets
 * for its commands, stays.
 */
export function commandEnv(env: Readonly<Record<string, string | undefined>>): Record<string, string> {
	const result: Record<string, string> = {};
	for (const [name, value] of Object.entries(env)) {
		if (value === undefined || AGENT_SOCKETS.has(name) || CREDENTIAL.test(name) || (PRIVATE_PREFIXES.test(name) && name !== 'OPENCODE_TERMINAL')) {
			continue;
		}
		result[name] = value;
	}
	return result;
}

/** The arguments OpenCode's and Dragon's file tools take a path in. */
const PATH_ARGUMENTS = ['path', 'filePath', 'file_path'];
/** The files a patch adds, changes, deletes or moves to. */
const PATCH_FILE = /^\*\*\* (?:(?:Add|Update|Delete) File|Move to): (?<file>.+)$/gm;

/** The paths one tool call names: its path arguments and the files its patch touches. */
function toolPaths(input: unknown): string[] {
	if (typeof input !== 'object' || input === null) {
		return [];
	}
	const args = input as Record<string, unknown>;
	const paths = PATH_ARGUMENTS.map(name => args[name]).filter((value): value is string => typeof value === 'string' && !!value.trim());
	if (typeof args.patchText === 'string') {
		paths.push(...[...args.patchText.matchAll(PATCH_FILE)].map(match => match.groups!.file.trim()));
	}
	return paths;
}

/** Where a path really leads: through every link, also one to a file not made yet. */
function realTarget(file: string, hops = 0): string {
	try {
		return realpathSync(file);
	} catch {
		// Missing, or a link to something missing, which writing it would make.
	}
	if (hops < 40) {
		try {
			return realTarget(path.resolve(path.dirname(file), readlinkSync(file)), hops + 1);
		} catch {
			// not a link
		}
	}
	const parent = path.dirname(file);
	return parent === file ? file : path.join(realTarget(parent, hops), path.basename(file));
}

/** A path as OpenCode's file tools take it: from the session's folder, `~` the home folder. */
function toolTarget(directory: string, value: string, home: string): string {
	const fromHome = value === '~' || value.startsWith('~/') || (process.platform === 'win32' && value.startsWith('~\\'));
	return path.resolve(directory, fromHome ? path.join(home, value.slice(2)) : value);
}

/**
 * Why a file tool call may not run: a path it names is in one of `folders` (the open folders, and
 * OpenCode's own that agents are let into) but a symbolic link there leads outside them, say one a
 * command made to `~/.ssh`. OpenCode's rules see only the path as written, and its tools follow
 * links. Paths outside the folders are left to those rules.
 */
export function linkedOutside(directory: string, input: unknown, folders: readonly string[], home = homedir()): string | undefined {
	const real = folders.map(folder => realTarget(folder));
	for (const value of toolPaths(input)) {
		const file = toolTarget(directory, value, home);
		if (![...folders, ...real].some(folder => inside(folder, file))) {
			continue;
		}
		if (!real.some(folder => inside(folder, realTarget(file)))) {
			return `${value} leads outside the folders open in the window through a symbolic link. Agents are kept to those folders.`;
		}
	}
	return undefined;
}

/** The folders of OpenCode's own that agents' file tools are let into (`confinementConfig`). */
export interface OpenCodeFolders {
	/** Where OpenCode saves long tool output, for every window and every project. */
	readonly toolOutput: string;
	/** Where it saves long shell output, a folder for each project. */
	readonly shell: string;
	/** Its temp folder, which it tells agents to use. */
	readonly tmp: string;
	/** Where the plan agent writes plans. */
	readonly plan: string;
}

/**
 * OpenCode's folders as its `Global` paths name them, for a server with these home, temp and data
 * folders: its data folder is in the home folder, its plan folder in its own home folder
 * (`OPENCODE_TEST_HOME`, when that is set).
 */
export function openCodeFolders(input: { readonly home: string; readonly tmpdir: string; readonly dataHome?: string; readonly openCodeHome?: string }): OpenCodeFolders {
	const data = path.join(input.dataHome || path.join(input.home, '.local', 'share'), 'opencode');
	return { toolOutput: path.join(data, 'tool-output'), shell: path.join(data, 'shell'), tmp: path.join(input.tmpdir, 'opencode'), plan: path.join(input.openCodeHome || input.home, '.opencode', 'plan') };
}

/** Every string in a value: the texts of a model request, wherever its format keeps them. */
function stringsIn(value: unknown, found: string[] = [], seen = new Set<object>()): string[] {
	if (typeof value === 'string') {
		found.push(value);
	} else if (typeof value === 'object' && value !== null && !seen.has(value)) {
		seen.add(value);
		for (const item of Object.values(value)) {
			stringsIn(item, found, seen);
		}
	}
	return found;
}

/**
 * The files in `saved` (where OpenCode saves long output) that a model request names: the output
 * OpenCode told the model it saved, `[… full output saved to <file>]`, which it may read.
 */
export function toldOutputs(request: unknown, saved: readonly string[]): string[] {
	const roots = [...new Set(saved.flatMap(folder => [folder, realTarget(folder)]))].map(root => root + path.sep);
	const told = new Set<string>();
	for (const text of stringsIn(request)) {
		for (const root of roots) {
			for (let at = text.indexOf(root); at >= 0; at = text.indexOf(root, at + root.length)) {
				// The folder as it is, as a home folder's name may hold a space; then the file's own name. Not
				// the folder found inside a longer path, as `/var/…` is in `/private/var/…`.
				const name = /^[^\s\]"'`<>|]*/.exec(text.slice(at + root.length))![0];
				if (name && (at === 0 || !/[\w.~/\\-]/.test(text[at - 1]))) {
					told.add(root + name);
				}
			}
		}
	}
	return [...told];
}

/**
 * Why a file tool call may not run: a path it names is in `saved`, where OpenCode saves long output
 * for every window and every project, but is not a file this window's models were told of
 * (`toldOutputs`). Those files' names cannot be guessed, so another's output stays closed as long
 * as the folders there are, which a read would list.
 */
export function savedElsewhere(directory: string, input: unknown, saved: readonly string[], told: Iterable<string>, home = homedir()): string | undefined {
	const roots = saved.flatMap(folder => [folder, realTarget(folder)]);
	let open: Set<string> | undefined;
	for (const value of toolPaths(input)) {
		const file = toolTarget(directory, value, home);
		const real = realTarget(file);
		if (!roots.some(root => inside(root, file) || inside(root, real))) {
			continue;
		}
		open ??= new Set([...told].map(name => realTarget(name)));
		// Never a folder, which would list others' output: a model could name one, whose name can be guessed, itself.
		if (!open.has(real) || statSync(real, { throwIfNoEntry: false })?.isDirectory()) {
			return `${value} is not output OpenCode saved for this window. Agents are kept to the folders open in the window and their own output.`;
		}
	}
	return undefined;
}

/** OpenCode's plan folder, and where Dragon records which folders each plan there was written from. */
export interface PlanFolder {
	/** Where the plan agent writes plans, a folder every project shares. */
	readonly plans: string;
	/** Where Dragon records the folders open in the window that wrote each plan: a folder no agent reaches. */
	readonly records: string;
}

/** What Dragon records of a plan. Real paths. */
interface PlanRecord {
	readonly file: string;
	readonly folders: readonly string[];
}

/** OpenCode's tools that make a file. */
const WRITERS = new Set(['write', 'edit', 'patch']);

/** A plan's record, by the plan's real path. */
function planRecord(records: string, file: string): string {
	return path.join(records, `${createHash('sha256').update(file).digest('hex').slice(0, 32)}.json`);
}

/** The record in a record file; none for one being written, or broken. */
function readPlanRecord(record: string): PlanRecord | undefined {
	try {
		const { file, folders }: Partial<PlanRecord> = JSON.parse(readFileSync(record, 'utf8'));
		return typeof file === 'string' && Array.isArray(folders) ? { file, folders: folders.filter(folder => typeof folder === 'string') } : undefined;
	} catch {
		return undefined;
	}
}

/** Whether a plan was written from a folder open in the window (real paths), or one in it. */
function writtenFrom(record: PlanRecord | undefined, open: readonly string[]): boolean {
	return !!record?.folders.some(folder => open.some(own => inside(own, folder)));
}

/**
 * Admits a file tool call to OpenCode's plan folder, which every project shares. Returns why the
 * call may not run: a path it names there is a plan not written from the folders open in the window,
 * as Dragon recorded, or a folder, which a read would list. Otherwise records the new plans the call
 * writes as written from those folders. A plan written before Dragon recorded them, or by OpenCode
 * outside Dragon, stays closed. When the plan folder is in an open folder, it is open as that is.
 */
export function admitPlans(directory: string, tool: string, input: unknown, plan: PlanFolder, folders: readonly string[], home = homedir()): string | undefined {
	const roots = [plan.plans, realTarget(plan.plans)];
	const open = folders.map(folder => realTarget(folder));
	if (open.some(folder => inside(folder, roots[1]))) {
		return undefined;
	}
	const made: string[] = [];
	for (const value of toolPaths(input)) {
		const file = toolTarget(directory, value, home);
		const real = realTarget(file);
		if (!roots.some(root => inside(root, file) || inside(root, real))) {
			continue;
		}
		const stat = statSync(real, { throwIfNoEntry: false });
		if (stat?.isDirectory()) {
			// None recorded yet, before the first plan: then the folder has no records.
			const names = existsSync(plan.records) ? readdirSync(plan.records) : [];
			const own = names
				.filter(name => name.endsWith('.json'))
				.map(name => readPlanRecord(path.join(plan.records, name)))
				.filter((record): record is PlanRecord => writtenFrom(record, open) && existsSync(record!.file))
				.map(record => record.file)
				.sort();
			return `${value} is a folder of plans, which every project shares. Agents are kept to the plans written from the folders open in the window${own.length ? `: ${own.join(', ')}` : ', and there are none yet'}.`;
		}
		if (!stat) {
			if (WRITERS.has(tool)) {
				made.push(real);
			}
		} else if (!writtenFrom(readPlanRecord(planRecord(plan.records, real)), open)) {
			return `${value} is a plan not written from the folders open in the window. Agents are kept to the plans written from them.`;
		}
	}
	for (const file of made) {
		mkdirSync(plan.records, { recursive: true });
		const record = planRecord(plan.records, file);
		const writing = `${record}.${process.pid}.tmp`;
		writeFileSync(writing, JSON.stringify({ file, folders: open } satisfies PlanRecord));
		renameSync(writing, record);
	}
	return undefined;
}

/** A skill as OpenCode lists it. */
export interface SkillEntry {
	readonly id: string;
	readonly path: string;
}

/** The path OpenCode gives its own skills, built into the binary. */
const BUILT_IN_SKILL = /^\/builtin\//;

/** True when `file` is outside the folders open in the window, through any link on its way. */
export function outsideFolders(file: string, folders: readonly string[]): boolean {
	const target = realTarget(file);
	return !folders.some(folder => inside(realTarget(folder), target));
}

/**
 * The skills outside the folders open in the window, such as the user's own in `~/.claude/skills`,
 * or reached from them through a link. OpenCode's own, built into it, are not.
 */
export function skillsOutside(skills: readonly SkillEntry[], folders: readonly string[]): string[] {
	return skills.filter(skill => !BUILT_IN_SKILL.test(skill.path) && outsideFolders(skill.path, folders)).map(skill => skill.id);
}

