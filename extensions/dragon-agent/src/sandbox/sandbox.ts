/**
 * Prepares one command: its environment loses what `commandEnv` drops, and, when the server was
 * given a sandbox, the command runs in it, with its own home folder. A sandbox whose files are gone
 * is not used, so commands keep working; it says why.
 */
export function confineCommand(event: ShellCreating, server: Readonly<Record<string, string | undefined>>): string | undefined {
	event.env = commandEnv(event.env);
	const profile = server.DRAGON_SANDBOX_PROFILE;
	const wrapper = server.DRAGON_SANDBOX_WRAPPER;
	const home = server.DRAGON_SANDBOX_HOME;
	if (!profile || !wrapper || !home) {
		return undefined;
	}
	if (!existsSync(profile) || !existsSync(wrapper)) {
		return `the sandbox for shell commands is missing (${existsSync(profile) ? wrapper : profile}); the command runs outside it`;
	}
	event.env = { ...event.env, HOME: home, DRAGON_SANDBOX_SHELL: event.shell, DRAGON_SANDBOX_PROFILE: profile };
	event.shell = wrapper;
	return undefined;
}

/**
 * Runs a command OpenCode spawns directly, not through the shell hook — a project's local MCP server
 * or a formatter — in the window's sandbox, as an agent's shell command is run. It prepends
 * `sandbox-exec` with the window's profile to the command, so the process is kept to the open
 * folders, and gives the home folder to set so `~` resolves inside the sandbox. It returns nothing
 * when there is no sandbox (off macOS, or Full Access, where the server was given none), so the
 * command runs as before; and a reason when the sandbox's files are gone, so the caller can say why
 * and let the command run rather than break it. `command[0]` is the executable.
 */
export function confineSpawn(command: readonly string[], server: Readonly<Record<string, string | undefined>>): { ok: true; command: string[]; home: string } | { ok: false; error: string } | undefined {
	const profile = server.DRAGON_SANDBOX_PROFILE;
	const home = server.DRAGON_SANDBOX_HOME;
	if (!profile || !home || !command.length) {
		return undefined;
	}
	if (!existsSync(profile)) {
		return { ok: false, error: `the sandbox is missing (${profile}); the command runs outside it` };
	}
	return { ok: true, command: [SANDBOX_EXEC, '-f', profile, ...command], home };
}

/** The wrapper OpenCode runs as the command's shell: it runs the real shell, with its arguments, in the sandbox. */
const WRAPPER = [
	'#!/bin/sh',
	'# Generated by Dragon IDE. Runs an agent\'s shell command in the sandbox Dragon made for its window.',
	'shell=$DRAGON_SANDBOX_SHELL',
	'profile=$DRAGON_SANDBOX_PROFILE',
	'unset DRAGON_SANDBOX_SHELL DRAGON_SANDBOX_PROFILE',
	`exec ${SANDBOX_EXEC} -f "$profile" "$shell" "$@"`,
	'',
].join('\n');

export interface PrepareSandboxInput {
	/** The folders open in the window and the folders of their agents' worktrees. */
	readonly folders: readonly string[];
	/** The real home folder. The profile, the wrapper and the commands' home folder are kept in it. */
	readonly home: string;
	readonly pathEnv: string;
	/** Folders closed besides the home folder. Default: `/Users` and `/Volumes`. */
	readonly closed?: readonly string[];
}

/** A folder's real path, also for one not made yet, such as a worktrees folder before the first worktree. */
function realFolder(folder: string): string {
	try {
		return realpathSync(folder);
	} catch {
		const parent = path.dirname(folder);
		return parent === folder ? folder : path.join(realFolder(parent), path.basename(folder));
	}
}

function run(file: string, args: readonly string[], cwd?: string, env?: NodeJS.ProcessEnv): Promise<{ code: number; stdout: string; stderr: string }> {
	return new Promise(resolve => {
		execFile(file, args, { cwd, env, timeout: 10_000 }, (err, stdout, stderr) => {
			resolve({ code: err ? (typeof err.code === 'number' ? err.code : 1) : 0, stdout: String(stdout), stderr: String(stderr || (err && !stderr ? err.message : '')) });
		});
	});
}

/**
 * Writes the profile, the wrapper and the commands' home folder for a window's folders, and checks
 * that `sandbox-exec` runs with them. Returns the variables for the server, or why there is no
 * sandbox: then commands run outside it, as they would without Dragon.
 */
export async function prepareSandbox(input: PrepareSandboxInput): Promise<{ ok: true; variables: SandboxVariables } | { ok: false; error: string }> {
	if (!existsSync(SANDBOX_EXEC)) {
		return { ok: false, error: `${SANDBOX_EXEC} was not found` };
	}
	const home = realFolder(input.home);
	const open = [...new Set(input.folders.map(realFolder))];
	// A folder may be a worktree of a repository elsewhere; Git needs the repository's folder.
	const gitFolders = await Promise.all(open.map(async folder => {
		const result = await run('git', ['rev-parse', '--path-format=absolute', '--git-common-dir'], folder);
		return result.code === 0 && result.stdout.trim() ? realFolder(result.stdout.trim()) : undefined;
	}));
	const folders = [...new Set([...open, ...gitFolders.filter((folder): folder is string => !!folder)])].sort();
	const id = createHash('sha1').update(folders.join('\n')).digest('hex').slice(0, 12);
	// In the closed home folder, so that no command changes the profile or the wrapper.
	const dir = path.join(home, '.dragon', 'sandbox');
	const commandHome = path.join(dir, 'homes', `${path.basename(open[0] ?? 'scratch')}-${id}`);
	await mkdir(commandHome, { recursive: true });
	// Commits made by agents keep the author's name; nothing else of the real Git config is read.
	const identity = await Promise.all(['user.name', 'user.email'].map(async key => [key, (await run('git', ['config', '--global', '--get', key])).stdout.trim()] as const));
	const gitconfig = identity.filter(([, value]) => value).map(([key, value]) => `\t${key.split('.')[1]} = ${JSON.stringify(value)}\n`).join('');
	await writeFile(path.join(commandHome, '.gitconfig'), gitconfig ? `[user]\n${gitconfig}` : '', 'utf8');
	const profile = sandboxProfile({
		folders,
		home: commandHome,
		readOnly: await toolchainFolders(input.pathEnv, home),
		closed: [...new Set([home, ...(input.closed ?? ['/Users', '/Volumes']).map(realFolder)])].sort(),
		// Also when the home folder itself is open.
		sealed: [path.join(dir, 'profiles')],
	});
	await mkdir(path.join(dir, 'profiles'), { recursive: true });
	const profileFile = path.join(dir, 'profiles', `${id}.sb`);
	const wrapper = path.join(dir, 'profiles', 'shell');
	await writeFile(profileFile, profile, 'utf8');
	if ((await readFile(wrapper, 'utf8').catch(() => undefined)) !== WRAPPER) {
		await writeFile(wrapper, WRAPPER, 'utf8');
	}
	await chmod(wrapper, 0o755);
	const probe = await run(wrapper, ['-c', 'exit 0'], undefined, { DRAGON_SANDBOX_SHELL: '/bin/sh', DRAGON_SANDBOX_PROFILE: profileFile });
	if (probe.code !== 0) {
		return { ok: false, error: `sandbox-exec did not run a command with the profile: ${probe.stderr.trim() || `exit ${probe.code}`}` };
	}
	return { ok: true, variables: { DRAGON_SANDBOX_PROFILE: profileFile, DRAGON_SANDBOX_WRAPPER: wrapper, DRAGON_SANDBOX_HOME: commandHome } };
}
