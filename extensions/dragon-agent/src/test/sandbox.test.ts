test('commands may read the toolchains on PATH in the home folder and the interpreters they link to, and not the folders around them', async () => {
	const home = realpathSync(mkdtempSync(path.join(tmpdir(), 'dragon-toolchains-')));
	try {
		// `~/.local/bin/python3.13` → `…/cpython-3.13/bin/python3.13`, where `cpython-3.13` → `cpython-3.13.14`.
		const store = path.join(home, '.local', 'share', 'uv', 'python');
		mkdirSync(path.join(store, 'cpython-3.13.14', 'bin'), { recursive: true });
		writeFileSync(path.join(store, 'cpython-3.13.14', 'bin', 'python3.13'), '');
		symlinkSync(path.join(store, 'cpython-3.13.14'), path.join(store, 'cpython-3.13'));
		mkdirSync(path.join(home, '.local', 'bin'), { recursive: true });
		symlinkSync(path.join(store, 'cpython-3.13', 'bin', 'python3.13'), path.join(home, '.local', 'bin', 'python3.13'));
		// `~/.cargo` also holds the crates.io token.
		mkdirSync(path.join(home, '.cargo', 'bin'), { recursive: true });
		writeFileSync(path.join(home, '.cargo', 'bin', 'cargo'), '');
		writeFileSync(path.join(home, '.cargo', 'credentials.toml'), '');
		mkdirSync(path.join(home, '.pyenv'));
		mkdirSync(path.join(home, 'notes'));
		const pathEnv = [path.join(home, '.local', 'bin'), path.join(home, '.cargo', 'bin'), '/usr/bin', home, 'relative/bin'].join(path.delimiter);
		assert.deepEqual((await toolchainFolders(pathEnv, home)).map(folder => path.relative(home, folder)), [
			'.cargo/bin',
			'.local/bin',
			'.local/share/uv/python',
			'.local/share/uv/python/cpython-3.13',
			'.local/share/uv/python/cpython-3.13.14',
			'.pyenv',
		]);
	} finally {
		rmSync(home, { recursive: true, force: true });
	}
});

