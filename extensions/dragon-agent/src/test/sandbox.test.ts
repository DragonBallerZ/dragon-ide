test('the sandbox plugin runs a project\'s local MCP server in the window\'s sandbox and leaves a remote one alone', async () => {
	const temp = mkdtempSync(path.join(tmpdir(), 'dragon-mcp-transform-'));
	const saved = { DRAGON_CONFINED_FOLDERS: process.env.DRAGON_CONFINED_FOLDERS, DRAGON_SANDBOX_PROFILE: process.env.DRAGON_SANDBOX_PROFILE, DRAGON_SANDBOX_HOME: process.env.DRAGON_SANDBOX_HOME };
	try {
		const workspace = path.join(temp, 'game');
		const profile = path.join(temp, 'window.sb');
		const home = path.join(temp, 'home');
		writeFileSync(profile, '(version 1)\n');
		process.env.DRAGON_CONFINED_FOLDERS = JSON.stringify([workspace]);
		process.env.DRAGON_SANDBOX_PROFILE = profile;
		process.env.DRAGON_SANDBOX_HOME = home;
		// The project's MCP servers: a local one that OpenCode spawns, a remote URL, and a local one whose
		// command is `opencode`, which OpenCode runs with BUN_BE_BUN set.
		const servers = new Map<string, McpServerConfig>([
			['fetch', { type: 'local', command: ['uvx', 'mcp-server-fetch'], environment: { TOKEN: 'keep' } }],
			['brave', { type: 'remote' }],
			['nested', { type: 'local', command: ['opencode', 'x', 'mcp'] }],
		]);
		const editor: McpEditor = {
			list: () => Array.from(servers),
			update: (name, update) => { const config = servers.get(name); if (config) { update(config); } },
		};
		await sandboxPlugin.setup({
			location: { directory: workspace },
			tool: { hook: async () => undefined },
			shell: { hook: async () => undefined },
			mcp: { transform: async callback => { await callback(editor); } },
		});
		assert.deepEqual(Object.fromEntries(servers), {
			fetch: { type: 'local', command: ['/usr/bin/sandbox-exec', '-f', profile, 'uvx', 'mcp-server-fetch'], environment: { TOKEN: 'keep', HOME: home } },
			brave: { type: 'remote' },
			nested: { type: 'local', command: ['/usr/bin/sandbox-exec', '-f', profile, 'opencode', 'x', 'mcp'], environment: { BUN_BE_BUN: '1', HOME: home } },
		});
	} finally {
		for (const [key, value] of Object.entries(saved)) {
			if (value === undefined) {
				delete process.env[key];
			} else {
				process.env[key] = value;
			}
		}
		rmSync(temp, { recursive: true, force: true });
	}
});

