test('in the sandbox, a command reaches the open folders and its own home, and nothing else in the home folder', { skip: process.platform !== 'darwin' && 'macOS only' }, async () => {
	const temp = realpathSync(mkdtempSync(path.join(tmpdir(), 'dragon-sandbox-')));
	// The home folder is in the temp folder, which commands may write to; the home folder still wins.
	const home = path.join(temp, 'home');
	const workspace = path.join(home, 'game');
	const second = path.join(temp, 'assets');
	const outside = path.join(home, 'private');
	try {
		for (const dir of [workspace, second, outside]) {
			mkdirSync(dir, { recursive: true });
		}
		writeFileSync(path.join(workspace, 'hello.txt'), 'hello\n');
		writeFileSync(path.join(outside, 'secret.txt'), 'secret\n');
		const outcomes = async (folders: string[], commands: readonly string[]) => {
			const prepared = await prepareSandbox({ folders, home, pathEnv: process.env.PATH ?? '', closed: [] });
			assert.ok(prepared.ok, JSON.stringify(prepared));
			const { DRAGON_SANDBOX_PROFILE, DRAGON_SANDBOX_WRAPPER, DRAGON_SANDBOX_HOME } = prepared.variables;
			return Object.fromEntries(commands.map(command => {
				const run = spawnSync(DRAGON_SANDBOX_WRAPPER, ['-c', command], {
					cwd: folders[0], encoding: 'utf8', timeout: 20_000,
					env: { PATH: process.env.PATH, HOME: DRAGON_SANDBOX_HOME, DRAGON_SANDBOX_SHELL: '/bin/sh', DRAGON_SANDBOX_PROFILE },
				});
				return [command, run.status === 0 ? 'ran' : 'refused'];
			}));
		};
		const profiles = path.join(home, '.dragon', 'sandbox', 'profiles');
		assert.deepEqual({
			open: await outcomes([workspace, second], [
				'cat hello.txt',
				'echo made > made.txt',
				`echo art > ${second}/art.txt`,
				'echo mine > "$HOME/mine.txt" && cat "$HOME/mine.txt"',
				'cat ../private/secret.txt',
				`ls ${outside}`,
				'echo planted > ../private/planted.txt',
				`echo changed >> ${profiles}/shell`,
			]),
			// With the home folder itself open, the sandbox's own files still cannot be changed.
			home: await outcomes([home], ['cat private/secret.txt', `echo changed >> ${profiles}/shell`]),
			planted: existsSync(path.join(outside, 'planted.txt')),
			wrapper: readFileSync(path.join(profiles, 'shell'), 'utf8').includes('changed'),
		}, {
			open: {
				'cat hello.txt': 'ran',
				'echo made > made.txt': 'ran',
				[`echo art > ${second}/art.txt`]: 'ran',
				'echo mine > "$HOME/mine.txt" && cat "$HOME/mine.txt"': 'ran',
				'cat ../private/secret.txt': 'refused',
				[`ls ${outside}`]: 'refused',
				'echo planted > ../private/planted.txt': 'refused',
				[`echo changed >> ${profiles}/shell`]: 'refused',
			},
			home: { 'cat private/secret.txt': 'ran', [`echo changed >> ${profiles}/shell`]: 'refused' },
			planted: false,
			wrapper: false,
		});
	} finally {
		rmSync(temp, { recursive: true, force: true });
	}
});
